#ifndef VXFEC_NCCL_GPU_KERNELS_H
#define VXFEC_NCCL_GPU_KERNELS_H

/*
 * Self-contained CUDA / HIP RTC C++ source for native NCCL/RCCL GPU FEC.
 * Uses zero external headers so both hiprtc (ROCm) and nvrtc (CUDA) compile it
 * directly in memory without SDK include paths.
 */
static const char g_vxfec_gpu_kernels_src[] =
    "typedef unsigned char vxf_u8;\n"
    "typedef unsigned short vxf_u16;\n"
    "typedef unsigned int vxf_u32;\n"
    "typedef unsigned long long vxf_u64;\n"
    "\n"
    "__device__ __forceinline__ vxf_u32 vxf_xtime4(vxf_u32 v)\n"
    "{\n"
    "    vxf_u32 m = v & 0x80808080u;\n"
    "    vxf_u32 sh = (v << 1u) & 0xfefefefeu;\n"
    "    vxf_u32 poly = m - (m >> 7u);\n"
    "    return sh ^ (poly & 0x1d1d1d1du);\n"
    "}\n"
    "\n"
    "__device__ __forceinline__ vxf_u32 vxf_shift4(vxf_u32 v)\n"
    "{\n"
    "    vxf_u32 v2 = vxf_xtime4(v);\n"
    "    vxf_u32 v4 = vxf_xtime4(v2);\n"
    "    return vxf_xtime4(vxf_xtime4(v4));\n"
    "}\n"
    "\n"
    "#define VXF_BUILD_NIB_TAB(tab, base_val) \\\n"
    "    tab[0] = 0u; \\\n"
    "    tab[1] = (base_val); \\\n"
    "    tab[2] = vxf_xtime4(tab[1]); \\\n"
    "    tab[3] = tab[2] ^ tab[1]; \\\n"
    "    tab[4] = vxf_xtime4(tab[2]); \\\n"
    "    tab[5] = tab[4] ^ tab[1]; \\\n"
    "    tab[6] = tab[4] ^ tab[2]; \\\n"
    "    tab[7] = tab[6] ^ tab[1]; \\\n"
    "    tab[8] = vxf_xtime4(tab[4]); \\\n"
    "    tab[9] = tab[8] ^ tab[1]; \\\n"
    "    tab[10] = tab[8] ^ tab[2]; \\\n"
    "    tab[11] = tab[10] ^ tab[1]; \\\n"
    "    tab[12] = tab[8] ^ tab[4]; \\\n"
    "    tab[13] = tab[12] ^ tab[1]; \\\n"
    "    tab[14] = tab[12] ^ tab[2]; \\\n"
    "    tab[15] = tab[14] ^ tab[1];\n"
    "\n"
    "__device__ __forceinline__ void vxf_accum_row8(\n"
    "    vxf_u32 w, vxf_u32 lo_w, vxf_u32 hi_w, vxf_u32 acc[8])\n"
    "{\n"
    "    if (((lo_w & 0xeeeeeeeeu) | hi_w) == 0u) {\n"
    "        if (lo_w & 0x00000001u) acc[0] ^= w;\n"
    "        if (lo_w & 0x00000010u) acc[1] ^= w;\n"
    "        if (lo_w & 0x00000100u) acc[2] ^= w;\n"
    "        if (lo_w & 0x00001000u) acc[3] ^= w;\n"
    "        if (lo_w & 0x00010000u) acc[4] ^= w;\n"
    "        if (lo_w & 0x00100000u) acc[5] ^= w;\n"
    "        if (lo_w & 0x01000000u) acc[6] ^= w;\n"
    "        if (lo_w & 0x10000000u) acc[7] ^= w;\n"
    "        return;\n"
    "    }\n"
    "    vxf_u32 tab[16];\n"
    "    vxf_u32 hi_base;\n"
    "    if (lo_w != 0u) {\n"
    "        VXF_BUILD_NIB_TAB(tab, w)\n"
    "        if (lo_w & 0xffffu) {\n"
    "            acc[0] ^= tab[lo_w & 0xfu];\n"
    "            acc[1] ^= tab[(lo_w >> 4u) & 0xfu];\n"
    "            acc[2] ^= tab[(lo_w >> 8u) & 0xfu];\n"
    "            acc[3] ^= tab[(lo_w >> 12u) & 0xfu];\n"
    "        }\n"
    "        if (lo_w >> 16u) {\n"
    "            acc[4] ^= tab[(lo_w >> 16u) & 0xfu];\n"
    "            acc[5] ^= tab[(lo_w >> 20u) & 0xfu];\n"
    "            acc[6] ^= tab[(lo_w >> 24u) & 0xfu];\n"
    "            acc[7] ^= tab[lo_w >> 28u];\n"
    "        }\n"
    "        hi_base = vxf_xtime4(tab[8]);\n"
    "    } else {\n"
    "        hi_base = vxf_shift4(w);\n"
    "    }\n"
    "    if (hi_w != 0u) {\n"
    "        VXF_BUILD_NIB_TAB(tab, hi_base)\n"
    "        if (hi_w & 0xffffu) {\n"
    "            acc[0] ^= tab[hi_w & 0xfu];\n"
    "            acc[1] ^= tab[(hi_w >> 4u) & 0xfu];\n"
    "            acc[2] ^= tab[(hi_w >> 8u) & 0xfu];\n"
    "            acc[3] ^= tab[(hi_w >> 12u) & 0xfu];\n"
    "        }\n"
    "        if (hi_w >> 16u) {\n"
    "            acc[4] ^= tab[(hi_w >> 16u) & 0xfu];\n"
    "            acc[5] ^= tab[(hi_w >> 20u) & 0xfu];\n"
    "            acc[6] ^= tab[(hi_w >> 24u) & 0xfu];\n"
    "            acc[7] ^= tab[hi_w >> 28u];\n"
    "        }\n"
    "    }\n"
    "}\n"
    "\n"
    "__device__ __forceinline__ void vxf_pack_mat_nib8(\n"
    "    const vxf_u8 *mat, vxf_u32 e_base, vxf_u32 tile_n, vxf_u32 row_stride, vxf_u32 col_idx,\n"
    "    vxf_u32 *out_lo, vxf_u32 *out_hi)\n"
    "{\n"
    "    vxf_u32 lo = 0u, hi = 0u;\n"
    "    for (vxf_u32 t = 0u; t < tile_n; t++) {\n"
    "        vxf_u8 ct = mat[(vxf_u64)(e_base + t) * row_stride + col_idx];\n"
    "        if (ct != 0u) {\n"
    "            vxf_u32 sh = 4u * t;\n"
    "            lo |= ((vxf_u32)(ct & 0x0fu)) << sh;\n"
    "            hi |= ((vxf_u32)(ct >> 4u)) << sh;\n"
    "        }\n"
    "    }\n"
    "    *out_lo = lo;\n"
    "    *out_hi = hi;\n"
    "}\n"
    "\n"
    "__device__ __forceinline__ vxf_u32 vxf_load_u32_clamped(const vxf_u8 *base, vxf_u64 off, vxf_u64 valid_bytes)\n"
    "{\n"
    "    if (off >= valid_bytes)\n"
    "        return 0u;\n"
    "    if (off + 4ULL <= valid_bytes && (((vxf_u64)(base + off)) & 3ULL) == 0ULL)\n"
    "        return *(const vxf_u32 *)(base + off);\n"
    "    vxf_u32 w = 0u;\n"
    "    for (vxf_u32 b = 0u; b < 4u && (off + b) < valid_bytes; b++)\n"
    "        w |= ((vxf_u32)base[off + b]) << (b * 8u);\n"
    "    return w;\n"
    "}\n"
    "\n"
    "__device__ __forceinline__ void vxf_store_u32_clamped(vxf_u8 *base, vxf_u64 off, vxf_u64 valid_bytes, vxf_u32 w)\n"
    "{\n"
    "    if (off >= valid_bytes)\n"
    "        return;\n"
    "    if (off + 4ULL <= valid_bytes && (((vxf_u64)(base + off)) & 3ULL) == 0ULL) {\n"
    "        *(vxf_u32 *)(base + off) = w;\n"
    "        return;\n"
    "    }\n"
    "    for (vxf_u32 b = 0u; b < 4u && (off + b) < valid_bytes; b++)\n"
    "        base[off + b] = (vxf_u8)((w >> (b * 8u)) & 0xffu);\n"
    "}\n"
    "\n"
    "extern \"C\" __global__ void vxfec_gf256_staged_kernel(\n"
    "    const vxf_u32 * __restrict__ in_words,\n"
    "    vxf_u32 * __restrict__ out_words,\n"
    "    const vxf_u8 * __restrict__ mat,\n"
    "    vxf_u32 row_beg,\n"
    "    vxf_u32 num_rows,\n"
    "    vxf_u32 num_out,\n"
    "    vxf_u32 in_stride_u32,\n"
    "    vxf_u32 out_stride_u32)\n"
    "{\n"
    "    vxf_u32 col = blockIdx.x * blockDim.x + threadIdx.x;\n"
    "    if (col >= out_stride_u32)\n"
    "        return;\n"
    "    vxf_u32 e_base = blockIdx.y * 8u;\n"
    "    vxf_u32 tile_n = (e_base + 8u <= num_out) ? 8u : ((e_base < num_out) ? (num_out - e_base) : 0u);\n"
    "    if (tile_n == 0u)\n"
    "        return;\n"
    "\n"
    "    if (col >= in_stride_u32) {\n"
    "        for (vxf_u32 t = 0u; t < tile_n; t++)\n"
    "            out_words[(vxf_u64)(e_base + t) * out_stride_u32 + col] = 0u;\n"
    "        return;\n"
    "    }\n"
    "\n"
    "    vxf_u32 acc[8] = {0u, 0u, 0u, 0u, 0u, 0u, 0u, 0u};\n"
    "    for (vxf_u32 r = row_beg; r < num_rows; r++) {\n"
    "        vxf_u32 lo_w = 0u, hi_w = 0u;\n"
    "        vxf_pack_mat_nib8(mat, e_base, tile_n, num_rows, r, &lo_w, &hi_w);\n"
    "        if ((lo_w | hi_w) == 0u)\n"
    "            continue;\n"
    "        vxf_u32 w = in_words[(vxf_u64)r * in_stride_u32 + col];\n"
    "        if (!w)\n"
    "            continue;\n"
    "        vxf_accum_row8(w, lo_w, hi_w, acc);\n"
    "    }\n"
    "    for (vxf_u32 t = 0u; t < tile_n; t++)\n"
    "        out_words[(vxf_u64)(e_base + t) * out_stride_u32 + col] = acc[t];\n"
    "}\n"
    "\n"
    "extern \"C\" __global__ void vxfec_gf256_vram_enc_kernel(\n"
    "    const vxf_u8 * __restrict__ src_bytes,\n"
    "    vxf_u64 valid_bytes,\n"
    "    vxf_u32 * __restrict__ out_words,\n"
    "    const vxf_u8 * __restrict__ mat,\n"
    "    vxf_u32 K,\n"
    "    vxf_u32 num_out,\n"
    "    vxf_u32 sym_T,\n"
    "    vxf_u32 out_stride_u32)\n"
    "{\n"
    "    vxf_u32 col = blockIdx.x * blockDim.x + threadIdx.x;\n"
    "    if (col >= out_stride_u32)\n"
    "        return;\n"
    "    vxf_u32 e_base = blockIdx.y * 8u;\n"
    "    vxf_u32 tile_n = (e_base + 8u <= num_out) ? 8u : ((e_base < num_out) ? (num_out - e_base) : 0u);\n"
    "    if (tile_n == 0u)\n"
    "        return;\n"
    "\n"
    "    vxf_u32 sym_u32 = sym_T >> 2u;\n"
    "    if (col >= sym_u32) {\n"
    "        for (vxf_u32 t = 0u; t < tile_n; t++)\n"
    "            out_words[(vxf_u64)(e_base + t) * out_stride_u32 + col] = 0u;\n"
    "        return;\n"
    "    }\n"
    "\n"
    "    vxf_u32 acc[8] = {0u, 0u, 0u, 0u, 0u, 0u, 0u, 0u};\n"
    "    vxf_u64 byte_col = (vxf_u64)col << 2u;\n"
    "    for (vxf_u32 k = 0u; k < K; k++) {\n"
    "        vxf_u32 lo_w = 0u, hi_w = 0u;\n"
    "        vxf_pack_mat_nib8(mat, e_base, tile_n, K, k, &lo_w, &hi_w);\n"
    "        if ((lo_w | hi_w) == 0u)\n"
    "            continue;\n"
    "        vxf_u32 w = vxf_load_u32_clamped(src_bytes, (vxf_u64)k * sym_T + byte_col, valid_bytes);\n"
    "        if (!w)\n"
    "            continue;\n"
    "        vxf_accum_row8(w, lo_w, hi_w, acc);\n"
    "    }\n"
    "    for (vxf_u32 t = 0u; t < tile_n; t++)\n"
    "        out_words[(vxf_u64)(e_base + t) * out_stride_u32 + col] = acc[t];\n"
    "}\n"
    "\n"
    "extern \"C\" __global__ void vxfec_gf256_vram_rep_kernel(\n"
    "    vxf_u8 * __restrict__ target_bytes,\n"
    "    vxf_u64 total_bytes,\n"
    "    const vxf_u32 * __restrict__ rep_words,\n"
    "    const vxf_u8 * __restrict__ mat,\n"
    "    const vxf_u32 * __restrict__ missing_esis,\n"
    "    vxf_u32 K,\n"
    "    vxf_u32 num_rep,\n"
    "    vxf_u32 num_out,\n"
    "    vxf_u32 sym_T)\n"
    "{\n"
    "    vxf_u32 sym_u32 = sym_T >> 2u;\n"
    "    vxf_u32 col = blockIdx.x * blockDim.x + threadIdx.x;\n"
    "    if (col >= sym_u32)\n"
    "        return;\n"
    "    vxf_u32 e_base = blockIdx.y * 8u;\n"
    "    vxf_u32 tile_n = (e_base + 8u <= num_out) ? 8u : ((e_base < num_out) ? (num_out - e_base) : 0u);\n"
    "    if (tile_n == 0u)\n"
    "        return;\n"
    "\n"
    "    vxf_u32 mat_cols = K + num_rep;\n"
    "    vxf_u32 acc[8] = {0u, 0u, 0u, 0u, 0u, 0u, 0u, 0u};\n"
    "    vxf_u64 byte_col = (vxf_u64)col << 2u;\n"
    "\n"
    "    for (vxf_u32 k = 0u; k < K; k++) {\n"
    "        vxf_u32 lo_w = 0u, hi_w = 0u;\n"
    "        vxf_pack_mat_nib8(mat, e_base, tile_n, mat_cols, k, &lo_w, &hi_w);\n"
    "        if ((lo_w | hi_w) == 0u)\n"
    "            continue;\n"
    "        vxf_u32 w = vxf_load_u32_clamped(target_bytes, (vxf_u64)k * sym_T + byte_col, total_bytes);\n"
    "        if (!w)\n"
    "            continue;\n"
    "        vxf_accum_row8(w, lo_w, hi_w, acc);\n"
    "    }\n"
    "\n"
    "    for (vxf_u32 r = 0u; r < num_rep; r++) {\n"
    "        vxf_u32 lo_w = 0u, hi_w = 0u;\n"
    "        vxf_pack_mat_nib8(mat, e_base, tile_n, mat_cols, K + r, &lo_w, &hi_w);\n"
    "        if ((lo_w | hi_w) == 0u)\n"
    "            continue;\n"
    "        vxf_u32 w = rep_words[(vxf_u64)r * sym_u32 + col];\n"
    "        if (!w)\n"
    "            continue;\n"
    "        vxf_accum_row8(w, lo_w, hi_w, acc);\n"
    "    }\n"
    "\n"
    "    for (vxf_u32 t = 0u; t < tile_n; t++) {\n"
    "        vxf_u32 dst_k = missing_esis[e_base + t];\n"
    "        vxf_store_u32_clamped(target_bytes, (vxf_u64)dst_k * sym_T + byte_col, total_bytes, acc[t]);\n"
    "    }\n"
    "}\n";

#endif /* VXFEC_NCCL_GPU_KERNELS_H */
